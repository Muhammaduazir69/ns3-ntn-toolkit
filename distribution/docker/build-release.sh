#!/usr/bin/env bash
# Build a clean, leak-safe release image of ns3-ntn-toolkit from COMMITTED source only.
#
# usage: distribution/docker/build-release.sh <version>      (e.g. 2.7.0; tags <version> and latest)
#
# The build context is staged from git, never from the working tree, so local run outputs,
# virtualenvs, drafts, paper folders and untracked files can not reach the image:
#   1. `git archive HEAD` of ns-3-dev (what the public repository holds);
#   2. each nested module repository under contrib/ overlaid with its own `git archive HEAD`
#      (some module files, e.g. the digital-twin API and the FlexRIC bridge, live only there);
#   3. the vendored SNS3 satellite tree (untracked in ns-3-dev; without it nothing builds);
#   4. paper and draft folders removed, then a leak check that aborts on any forbidden path.
set -euo pipefail
VER=${1:?usage: build-release.sh <version>}
IMG=uzairdocker69/ns3-ntn-toolkit
SRC=$(cd "$(dirname "$0")/../.." && pwd)            # .../ns-3-dev
CTX=$(dirname "$SRC")/.docker-ctx
say() { printf '\n== %s\n' "$*"; }

[ -z "$(git -C "$SRC" status --porcelain --untracked-files=no)" ] || { echo "ns-3-dev has uncommitted changes; commit first"; exit 1; }

say "staging context in $CTX"
rm -rf "$CTX"; mkdir -p "$CTX/ns-3-dev"
git -C "$SRC" archive HEAD | tar -x -C "$CTX/ns-3-dev"
for g in "$SRC"/contrib/*/.git; do
  m=$(basename "$(dirname "$g")")
  [ "$m" = satellite ] && continue
  git -C "$SRC/contrib/$m" archive HEAD | tar -x -C "$CTX/ns-3-dev/contrib/$m"
  echo "  overlaid contrib/$m @ $(git -C "$SRC/contrib/$m" rev-parse --short HEAD)"
done
# data/sims holds 1.4 GB of SNS3 sample outputs; SNS3 only needs the directory to exist (it writes there).
rsync -a --exclude=.git --exclude='data/sims' "$SRC/contrib/satellite/" "$CTX/ns-3-dev/contrib/satellite/"
mkdir -p "$CTX/ns-3-dev/contrib/satellite/data/sims"
# The nr patch series is gitignored (*.patch) but is part of the public source.
rsync -a "$SRC/contrib/nr/ntn-patches/" "$CTX/ns-3-dev/contrib/nr/ntn-patches/"

say "removing paper and draft folders"
find "$CTX/ns-3-dev" -type d \( -name paper -o -name papers -o -name drafts -o -name _archive_v1 \) -prune -exec rm -rf {} +
rm -f "$CTX"/ns-3-dev/docs/paper*
# Generated protobuf code is regenerated by the image's own protoc (host protoc output does not compile there).
find "$CTX/ns-3-dev" \( -name '*.pb.cc' -o -name '*.pb.h' -o -name '*_pb2.py' -o -name '*.egg-info' -o -name __pycache__ \) -prune -exec rm -rf {} +

say "leak check"
bad=$(cd "$CTX/ns-3-dev" && find . \( -iname '*paper*' -o -iname 'AUDIT_*' -o -iname 'AI_NATIVE_*' -o -iname 'PROTOCOL_FIDELITY_*' \
        -o -iname 'ROADMAP*' -o -iname '*SCALING_PLAN*' -o -iname '*control-center*' -o -iname 'ntn_cc' -o -name '.env' \
        -o -name '*.pem' -o -name 'id_rsa*' -o -name '.venv' \) -not -path './contrib/satellite/*' | head -20)
[ -z "$bad" ] || { echo "forbidden paths in context:"; echo "$bad"; exit 1; }
# (the public local-dev InfluxDB init token in the compose files is not a secret; this script names the patterns itself)
if grep -rIn -E 'uzair_aerospace|89\.167\.96\.121|ADMIN_TOKEN|BEGIN (RSA|OPENSSH) PRIVATE' "$CTX/ns-3-dev" --exclude-dir=satellite \
     --exclude=build-release.sh 2>/dev/null | grep -v 'DOCKER_INFLUXDB_INIT_ADMIN_TOKEN' | head -5 | grep .; then
  echo "secret-looking strings in context"; exit 1; fi
du -sh "$CTX/ns-3-dev" "$CTX/ns-3-dev/contrib/satellite"

say "docker build $IMG:$VER"
DOCKER_BUILDKIT=1 docker build -t "$IMG:$VER" -t "$IMG:latest" -f "$SRC/distribution/docker/Dockerfile" "$CTX"
docker image inspect "$IMG:$VER" --format 'user={{.Config.User}} cmd={{json .Config.Cmd}} size={{.Size}}'
